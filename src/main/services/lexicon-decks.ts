export interface LexiconImportInput {
  dictId: string;
  deckId: string | null;
  deckName: string | null;
  filterMode: 'prefix' | 'list';
  prefix: string;
  wordList: string[];
  limit: number;
  reversed: boolean | null;
  language: 'ar' | 'en';
}

export function validateLexiconImportInput(input: unknown): LexiconImportInput {
  const v = (input ?? {}) as Record<string, unknown>;
  const allowed = ['dictId', 'deckId', 'deckName', 'filterMode', 'prefix', 'wordList', 'limit', 'reversed', 'language'];
  if (Object.keys(v).some(k => !allowed.includes(k))) throw new Error('invalid-request');
  if (typeof v.dictId !== 'string' || !SAFE_ID.test(v.dictId)) throw new Error('invalid-request');
  const deckId = v.deckId !== undefined && v.deckId !== null && v.deckId !== '' ? String(v.deckId) : null;
  if (deckId !== null && !SAFE_ID.test(deckId)) throw new Error('invalid-request');
  const deckName = typeof v.deckName === 'string' && v.deckName.trim() ? v.deckName.trim() : null;
  if (deckName && deckName.length > 200) throw new Error('invalid-request');
  if (!deckId && !deckName) throw new Error('invalid-request');
  const filterMode = v.filterMode === 'list' ? 'list' : 'prefix';
  const prefix = typeof v.prefix === 'string' ? v.prefix.trim().slice(0, 120) : '';
  let wordList: string[] = [];
  if (Array.isArray(v.wordList)) {
    wordList = v.wordList
      .filter((w): w is string => typeof w === 'string')
      .map(w => w.trim())
      .filter(Boolean)
      .slice(0, MAX_LEXICON_LIMIT);
  } else if (typeof v.wordList === 'string') {
    wordList = v.wordList
      .split(/[\r\n,،;\t]+/u)
      .map(w => w.trim())
      .filter(Boolean)
      .slice(0, MAX_LEXICON_LIMIT);
  }
  const rawLimit = v.limit === undefined ? DEFAULT_LEXICON_LIMIT : Number(v.limit);
  if (!Number.isInteger(rawLimit) || rawLimit < 1 || rawLimit > MAX_LEXICON_LIMIT) throw new Error('invalid-request');
  const reversed = typeof v.reversed === 'boolean' ? v.reversed : null;
  const language = v.language === 'ar' ? 'ar' : 'en';
  return { dictId: v.dictId, deckId, deckName, filterMode, prefix, wordList, limit: rawLimit, reversed, language };
}

export interface QuickAddLookupInput {
  word: string;
  meaning: string;
  source: string;
  kind: 'dictionary' | 'quran-word';
  deckId: string | null;
  reversed: boolean;
  language: 'ar' | 'en';
}

export function validateQuickAddLookupInput(input: unknown): QuickAddLookupInput {
  const v = (input ?? {}) as Record<string, unknown>;
  const allowed = ['word', 'meaning', 'source', 'kind', 'deckId', 'reversed', 'language'];
  if (Object.keys(v).some(k => !allowed.includes(k))) throw new Error('invalid-request');
  if (typeof v.word !== 'string' || !v.word.trim() || v.word.length > 300) throw new Error('invalid-request');
  if (typeof v.meaning !== 'string' || !v.meaning.trim() || v.meaning.length > 10_000) throw new Error('invalid-request');
  if (typeof v.source !== 'string' || !v.source.trim() || v.source.length > 300) throw new Error('invalid-request');
  const kind = v.kind === 'quran-word' ? 'quran-word' : 'dictionary';
  if (kind === 'quran-word' && !isSafeNonHifzVocabularyWord(v.word)) {
    throw new Error('hifz-guardrail');
  }
  const deckId = v.deckId !== undefined && v.deckId !== null && v.deckId !== '' ? String(v.deckId) : null;
  if (deckId !== null && !SAFE_ID.test(deckId)) throw new Error('invalid-request');
  const reversed = v.reversed !== false;
  const language = v.language === 'ar' ? 'ar' : 'en';
  return {
    word: v.word.trim(),
    meaning: v.meaning.trim(),
    source: v.source.trim(),
    kind,
    deckId,
    reversed,
    language,
  };
}

export interface RootCardInput {
  root: string;
  deckId: string | null;
  deckName: string | null;
  language: 'ar' | 'en';
}

export function validateRootCardInput(input: unknown): RootCardInput {
  const v = (input ?? {}) as Record<string, unknown>;
  const allowed = ['root', 'deckId', 'deckName', 'language'];
  if (Object.keys(v).some(k => !allowed.includes(k))) throw new Error('invalid-request');
  if (typeof v.root !== 'string' || !v.root.trim() || v.root.length > 60) throw new Error('invalid-request');
  const letters = extractRootLetters(v.root);
  if (letters.length < 2 || letters.length > 7) throw new Error('invalid-request');
  const deckId = v.deckId !== undefined && v.deckId !== null && v.deckId !== '' ? String(v.deckId) : null;
  if (deckId !== null && !SAFE_ID.test(deckId)) throw new Error('invalid-request');
  const deckName = typeof v.deckName === 'string' && v.deckName.trim() ? v.deckName.trim().slice(0, 200) : null;
  const language = v.language === 'ar' ? 'ar' : 'en';
  return { root: v.root.trim(), deckId, deckName, language };
}

export interface RootDeckInput {
  deckName: string;
  surah: number | null;
  limit: number;
  language: 'ar' | 'en';
}

export function validateRootDeckInput(input: unknown): RootDeckInput {
  const v = (input ?? {}) as Record<string, unknown>;
  const allowed = ['deckName', 'surah', 'limit', 'language'];
  if (Object.keys(v).some(k => !allowed.includes(k))) throw new Error('invalid-request');
  if (typeof v.deckName !== 'string' || !v.deckName.trim() || v.deckName.length > 200) throw new Error('invalid-request');
  let surah: number | null = null;
  if (v.surah !== undefined && v.surah !== null && v.surah !== '' && v.surah !== 0) {
    const s = Number(v.surah);
    if (!Number.isInteger(s) || s < 1 || s > 114) throw new Error('invalid-request');
    surah = s;
  }
  const rawLimit = v.limit === undefined ? 50 : Number(v.limit);
  if (!Number.isInteger(rawLimit) || rawLimit < 1 || rawLimit > MAX_ROOT_DECK_LIMIT) throw new Error('invalid-request');
  const language = v.language === 'ar' ? 'ar' : 'en';
  return { deckName: v.deckName.trim(), surah, limit: rawLimit, language };
}

