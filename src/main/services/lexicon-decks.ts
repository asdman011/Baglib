/**
 * Baglib — Lexicon vocabulary, translation cards, quick-add from lookups, Quranic roots & tafsir (KEY-400).
 *
 * - Stage 1 & 2 (Lexicon import & translation cards): imports headwords in pages from an installed
 *   dictionary into a revision deck, writing in batched transactions. Uses `stock-basic`, or
 *   `stock-basic-reversed` when `source_lang !== target_lang` (or requested by the user).
 *   Strips HTML safely to plain text so no script, style, or on* attributes survive.
 *   Re-importing adds only missing headwords and preserves the existing FSRS schedule (`source_ref`
 *   `lexicon:<dictId>:<headword>`).
 * - Stage 3 (Quick-add from lookups): compact one-click save of `word ↔ meaning` into a chosen
 *   deck (remembering the last deck in `revision.quickAdd.lastDeckId`), from reader dictionary
 *   lookups or Quran word-by-word / morphology lookups (`sura:ayah` as source). Duplicate in the
 *   same deck returns `{ duplicate: true }` ("already in deck").
 * - Stage 4 (Quranic root cards / ishtiqaq): front = root with dashes (e.g. `أ-ل-ه`); back = the
 *   root's meaning from an installed Arabic lexicon (never generated by AI or written by hand),
 *   plus a short list of Quran words from that root with their counts (KEY-252 frequency). If no
 *   installed lexicon defines the root, the back holds only the word list and states that no
 *   lexicon source text is installed. Also generates a root deck for a sura or the N most frequent
 *   roots.
 * - Stage 5 (Tafsir cards): generates cards from the user's highlights and comments in tafsir
 *   books in the library (and QUL tafsir / personal commentary on Quran ayahs): front = ayah
 *   reference (or page/title) + first words of the highlight; back = highlighted tafsir text +
 *   user's comment + tafsir source name. Regenerating updates in place and keeps the schedule.
 * - Strict guardrail (no hifz): no card may show Quran text to be memorised or recited from memory.
 */

