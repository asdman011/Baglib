const SAFE_ID = /^[A-Za-z0-9_-]{1,128}$/u;

const escapeHtml = (text: string) =>
  text
    .replace(/&/gu, '&amp;')
    .replace(/</gu, '&lt;')
    .replace(/>/gu, '&gt;')
    .replace(/"/gu, '&quot;')
    .replace(/\r?\n/gu, '<br>');

/**
 * Safely strips dictionary HTML to clean plain text.
 * Removes `<script>`, `<style>`, `<iframe>`, `<object>`, `<embed>`, `<svg>` and all attributes/tags,
 * preserving line breaks for block elements and `<br>`.
 */
export function stripDictionaryHtml(raw: string, maxChars = MAX_DEFINITION_CHARS): string {
  if (!raw || typeof raw !== 'string') return '';
  const bounded = raw.slice(0, 100_000);
  const preCleaned = bounded
    .replace(/<script\b[\s\S]*?<\/script>/giu, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/giu, ' ')
    .replace(/<(?:br|p|div|li|tr|dd|dt|h[1-6])\b[^>]*>/giu, '\n');
  const { document } = parseHTML(`<html><body>${preCleaned}</body></html>`);
  for (const el of document.querySelectorAll('script, style, iframe, object, embed, noscript')) {
    el.remove();
  }
  const text = (document.body?.textContent ?? '')
    .replace(/[ \t\f\v]+/gu, ' ')
    .replace(/\n[ \t]+/gu, '\n')
    .replace(/\n{3,}/gu, '\n\n')
    .trim();
  if (text.length <= maxChars) return text;
  return `${text.slice(0, maxChars).trimEnd()}…`;
}

/**
 * Formats an Arabic root with dashes, e.g. "أ ل ه" or "أله" -> "أ-ل-ه".
 */
export function formatDashedRoot(root: string): string {
  const letters = extractRootLetters(root);
  return letters.length >= 2 ? letters.join('-') : root.trim();
}

export function extractRootLetters(root: string): string[] {
  const cleaned = stripArabicDiacritics(root).replace(/[-–—\s·.،,]+/gu, ' ').trim();
  if (!cleaned) return [];
  const tokens = cleaned.split(/\s+/u).filter(Boolean);
  if (tokens.length >= 2) return tokens.flatMap(t => (t.length > 1 ? [...t] : [t]));
  return [...cleaned.replace(/\s+/gu, '')];
}

/**
 * Guardrail check: ensures a vocabulary or root card never stores a full multi-word Quranic verse
 * to be recited or memorised from memory.
 */
export function isSafeNonHifzVocabularyWord(word: string): boolean {
  const trimmed = word.trim();
  if (!trimmed) return false;
  // A single lexical item (or root/collocation up to 3 tokens) is vocabulary; 4+ Arabic words or ayah markers is verse text.
  if (/[\u06DD\u06DE۞۩]/u.test(trimmed)) return false;
  const words = trimmed.split(/\s+/u).filter(Boolean);
  return words.length <= 3;
}

