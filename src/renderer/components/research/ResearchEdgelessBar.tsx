'use client';

import React from 'react';
import { translations } from '../../translations';
import {
  Link2,
  LayoutGrid,
  Layers,
  Undo2,
  Maximize2,
  Minus,
  Plus,
  ExternalLink,
  Sparkles,
} from 'lucide-react';

interface Props {
  language: 'ar' | 'en';
  onFitScreen?: () => void;
  onInsertKanban?: () => void | Promise<unknown>;
  onArrangeSources?: () => void | Promise<unknown>;
  onUndoArrange?: () => void | Promise<unknown>;
  onLinkBoard?: () => void;
  onLinkCanvas?: () => void;
  hasGeneratedFrames?: boolean;
  zoomLevel?: number;
  onZoomIn?: () => void;
  onZoomOut?: () => void;
  onSelectTool?: (tool: string) => void;
  activeTool?: string;
}

export function ResearchEdgelessBar({
  language,
  onFitScreen,
  onInsertKanban,
  onArrangeSources,
  onUndoArrange,
  onLinkBoard,
  onLinkCanvas,
  hasGeneratedFrames = false,
  zoomLevel = 100,
  onZoomIn,
  onZoomOut,
}: Props) {
  const t = translations[language];

  return (
    <>
      {/* Top-start BagLib Canvas Actions Pill (kept clear of BlockSuite's bottom edgeless-toolbar) */}
      <div className="research-canvas-actions-bar pointer-events-auto" role="toolbar" aria-label={t.researchEdgelessMode}>
        {onLinkCanvas && (
          <button
            type="button"
            onClick={onLinkCanvas}
            data-action="canvas-link"
            className="research-toolbar-btn"
            title={t.researchCanvasLinkTitle}
            aria-label={t.researchCanvasLinkTitle}
          >
            <Link2 className="w-4 h-4 text-sky-400" />
          </button>
        )}

        {onInsertKanban && (
          <button
            type="button"
            onClick={() => void onInsertKanban()}
            data-action="insert-kanban"
            className="research-toolbar-btn"
            title={t.researchToolKanban}
            aria-label={t.researchToolKanban}
          >
            <LayoutGrid className="w-4 h-4 text-amber-500" />
          </button>
        )}

        {onArrangeSources && (
          <button
            type="button"
            onClick={() => void onArrangeSources()}
            data-action="arrange-sources"
            className="research-toolbar-btn"
            title={t.editorArrangeSources}
            aria-label={t.editorArrangeSources}
          >
            <Layers className="w-4 h-4 text-emerald-500" />
          </button>
        )}

        {onUndoArrange && (
          <button
            type="button"
            onClick={() => void onUndoArrange()}
            data-action="undo-arrange"
            className="research-toolbar-btn"
            title={t.editorUndoArrange}
            aria-label={t.editorUndoArrange}
          >
            <Undo2 className="w-4 h-4 text-rose-500" />
          </button>
        )}

        {onLinkBoard && (
          <button
            type="button"
            onClick={onLinkBoard}
            data-action="link-board"
            className="research-toolbar-btn"
            title={t.editorLinkBoard}
            aria-label={t.editorLinkBoard}
          >
            <ExternalLink className="w-4 h-4 text-primary" />
          </button>
        )}

        {hasGeneratedFrames && (
          <span
            data-canvas-generated-badge
            className="inline-flex items-center gap-1 rounded-md bg-emerald-500/15 px-2 py-0.5 text-[11px] font-medium text-emerald-400 border border-emerald-500/30"
          >
            <Sparkles className="w-3 h-3" />
            {t.researchCanvasAutoGenerated}
          </span>
        )}
      </div>

      {/* Bottom-start zoom controls */}
      <div className="research-zoom-controls-dock pointer-events-auto" role="toolbar" aria-label={t.boardsZoomLevel || 'Zoom'}>
        <button
          type="button"
          onClick={onFitScreen}
          className="research-zoom-btn"
          title={t.researchZoomFit}
          aria-label={t.researchZoomFit}
        >
          <Maximize2 className="w-3.5 h-3.5" />
        </button>
        <button
          type="button"
          onClick={onZoomOut}
          className="research-zoom-btn"
          title={t.researchZoomOut}
          aria-label={t.researchZoomOut}
        >
          <Minus className="w-3.5 h-3.5" />
        </button>
        <span className="research-zoom-text" aria-live="polite">
          {Math.round(zoomLevel)}%
        </span>
        <button
          type="button"
          onClick={onZoomIn}
          className="research-zoom-btn"
          title={t.researchZoomIn}
          aria-label={t.researchZoomIn}
        >
          <Plus className="w-3.5 h-3.5" />
        </button>
      </div>
    </>
  );
}
