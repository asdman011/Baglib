function applyLanguageFromQuery() {
  // Until the RE-2 host writes lang/dir itself, ?lang=ar lets the smoke test check RTL.
  const lang = new URLSearchParams(location.search).get('lang');
  if (lang === 'ar' || lang === 'en') {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }
}

const blobs = bridge ? new BaglibBlobSource(bridge.blobs) : undefined;

function createWorkspace() {
  const workspace = new TestWorkspace({
    id: 'baglib-research',
    idGenerator: nanoid,
    // Standalone smoke tests use memory. Hosted documents use the parent filesystem bridge.
    blobSources: { main: blobs ?? new MemoryBlobSource() },
  });
  workspace.storeExtensions = [...storeManager.get('store'), ...sourceStoreExtensions(), ...noteEmbedStoreExtensions(), ...apparatusStoreExtensions()];
  workspace.start();
  workspace.meta.initialize();
  return workspace;
}

function createEmptyDoc(workspace: TestWorkspace, id: string): Store {
  const doc = workspace.createDoc(id);
  const store = doc.getStore({ id });
  doc.load(() => {
    const rootId = store.addBlock('affine:page', { title: new Text() });
    store.addBlock('affine:surface', {}, rootId);
    const noteId = store.addBlock('affine:note', {}, rootId);
    store.addBlock('affine:paragraph', {}, noteId);
  });
  store.resetHistory();
  return store;
}

function editorSettings() {
  const initial = Object.entries(GeneralSettingSchema.shape).reduce((acc, [key, schema]) => {
    (acc as Record<string, unknown>)[key] = schema.parse(undefined);
    return acc;
  }, {} as EditorSetting);
  return new Signal<EditorSetting>(initial);
}

function docModeProvider(editor: TestAffineEditorContainer): DocModeProvider {
  const primary = new Map<string, DocMode>();
  const changes = new Map<string, Subject<DocMode>>();
  const provider: DocModeProvider = {
    getPrimaryMode: docId => primary.get(docId) ?? 'page',
    setPrimaryMode: (mode, docId) => {
      primary.set(docId, mode);
      changes.get(docId)?.next(mode);
    },
    togglePrimaryMode: docId => {
      const mode = provider.getPrimaryMode(docId) === 'page' ? 'edgeless' : 'page';
      provider.setPrimaryMode(mode, docId);
      return mode;
    },
    onPrimaryModeChange: (handler, docId) => {
      if (!changes.has(docId)) changes.set(docId, new Subject());
      return changes.get(docId)!.subscribe(handler);
    },
    getEditorMode: () => editor.mode,
    setEditorMode: mode => editor.switchEditor(mode),
  };
  return provider;
}

async function mount() {
  if (!bridge) applyLanguageFromQuery();
  const app = document.getElementById('app');
  if (!app) throw new Error('#app not found');

  let workspace = createWorkspace();
  const store = createEmptyDoc(workspace, 'doc:home');
  store.get(FeatureFlagService).setFlag('enable_advanced_block_visibility', true);

  const editor = document.createElement('affine-editor-container') as TestAffineEditorContainer;
  editor.autofocus = true;
  editor.doc = store;

  const common: ExtensionType[] = [
    ...sourceViewExtensions(),
    ...noteEmbedViewExtensions(),
    ...canvasExtensions(),
    ...apparatusViewExtensions(),
    FontConfigExtension(BaglibCanvasTextFonts),
    EditorSettingExtension({ setting$: editorSettings() }),
    ParseDocUrlExtension({ parseDocUrl: () => undefined }),
    { setup: di => di.override(DocModeProvider, docModeProvider(editor)) },
  ];

  editor.pageSpecs = [...viewManager.get('page'), ...common];
  editor.edgelessSpecs = [...viewManager.get('edgeless'), ...common];

  app.append(document.createElement('baglib-scholarly-toolbar'), editor, document.createElement('baglib-footnote-list'));
  await editor.updateComplete;
  standaloneApparatus(store);
  const stopApparatusAppearance = bridge?.subscribeAppearance(refreshApparatus);

  const schema = new Schema();
  schema.register([...AffineSchemas, ...sourceSchemas, noteEmbedSchema, ...apparatusSchemas]);

  const transformer = () => new Transformer({
    schema,
    blobCRUD: workspace.blobSync,
    docCRUD: {
      create: (id: string) => workspace.createDoc(id).getStore({ id }),
      get: (id: string) => workspace.getDoc(id)?.getStore({ id }) ?? null,
      delete: (id: string) => workspace.removeDoc(id),
    },
  });
  let current: ManuscriptDocument | undefined;
  let loading = false;
  let scheduled: Promise<void> = Promise.resolve();
  const seenMindmaps = new Set<string>();
  const syncMindmapRtlDefault = (doc: Store, isInitialLoad: boolean) => {
    const surface = doc.getModelsByFlavour('affine:surface')[0] as unknown as {
      elementModels?: Array<{ id: string; type: string; layoutType?: number }>;
      updateElement?: (id: string, props: Record<string, unknown>) => void;
    } | undefined;
    if (!surface?.elementModels) return;
    const rtl = document.documentElement.dir === 'rtl' || document.documentElement.lang === 'ar';
    for (const el of surface.elementModels) {
      if (el.type !== 'mindmap') continue;
      if (isInitialLoad) {
        seenMindmaps.add(el.id);
      } else if (!seenMindmaps.has(el.id)) {
        seenMindmaps.add(el.id);
        if (rtl && el.layoutType === 0 && surface.updateElement) {
          surface.updateElement(el.id, { layoutType: 1 });
        }
      }
    }
  };
  const changed = () => {
    if (!loading) syncMindmapRtlDefault(editor.doc, false);
    refreshApparatus();
    if (loading || !current || !bridge) return;
    const id = current.id;
    scheduled = scheduled.catch(() => undefined).then(() => {
      if (loading || current?.id !== id) return;
      const snapshot = transformer().docToSnapshot(editor.doc);
      if (!snapshot) throw new Error('snapshot-export-failed');
      bridge.change(id, JSON.stringify(snapshot), editor.mode);
    });
    void scheduled.catch(bridge.error);
  };
  let observedDoc = store.spaceDoc;
  observedDoc.on('update', changed);
  const session = {
    async load(value: ManuscriptDocument) {
      loading = true;
      const previous = workspace;
      observedDoc.off('update', changed);
      const next = createWorkspace();
      workspace = next;
      try {
        const snapshot = JSON.parse(value.snapshot);
        const loaded = await transformer().snapshotToDoc(snapshot);
        if (!loaded) throw new Error('snapshot-import-failed');
        workspace.meta.setDocMeta(value.id, snapshot.meta);
        loaded.get(FeatureFlagService).setFlag('enable_advanced_block_visibility', true);
        loaded.resetHistory();
        await loadApparatus(loaded, value.manuscript_id);
        editor.doc = loaded;
        seenMindmaps.clear();
        syncMindmapRtlDefault(loaded, true);
        editor.switchEditor(value.primary_mode);
        await editor.updateComplete;
        refreshApparatus();
        current = value;
        previous.forceStop(); previous.dispose();
        scheduled = Promise.resolve();
        observedDoc = loaded.spaceDoc;
        observedDoc.on('update', changed);
      } catch (error) {
        next.forceStop(); next.dispose(); workspace = previous; observedDoc.on('update', changed);
        throw error;
      } finally { loading = false; }
    },
    setReadonly(value: boolean) { editor.doc.readonly = value; },
    setMode(mode: DocMode) {
      editor.switchEditor(mode);
      return editor.updateComplete;
    },
    async arrangeSources(options?: { lang?: 'ar' | 'en' }) {
      const lang = options?.lang ?? bridge?.appearance?.()?.lang ?? ((document.documentElement.lang === 'ar' || document.documentElement.dir === 'rtl') ? 'ar' : 'en');
      return arrangeSourcesOnCanvas(editor.doc, editor, { ...options, lang });
    },
    async undoArrange() {
      return undoArrangeSources(editor.doc, editor);
    },
    async insertSource(kind: string, props: Record<string, unknown>) {
      // KEY-370: "Send to manuscript" into the chapter open here, so the next autosave keeps it.
      let note = editor.doc.root?.children.find(child => child.flavour === 'affine:note');
      if (!note && editor.doc.root) {
        const noteId = editor.doc.addBlock('affine:note', { xywh: '[0,0,520,260]' }, editor.doc.root.id);
        note = editor.doc.getModelById(noteId) ?? undefined;
      }
      if (!note) throw new Error('missing-note-block');
      return editor.doc.addBlock('baglib:' + kind, JSON.parse(JSON.stringify(props)), note);
    },
    async insertCanvasLink(target: { url: string; title: string; kind: 'note' | 'source'; noteId?: string }) {
      let note = editor.doc.root?.children.find(child => child.flavour === 'affine:note');
      if (!note && editor.doc.root) {
        const noteId = editor.doc.addBlock('affine:note', { xywh: '[0,0,520,260]' }, editor.doc.root.id);
        note = editor.doc.getModelById(noteId) ?? undefined;
      }
      if (!note) throw new Error('missing-note-block');
      editor.doc.captureSync();
      let blockId: string;
      if (target.kind === 'note' && target.noteId) {
        blockId = editor.doc.addBlock(
          NOTE_EMBED_FLAVOUR,
          noteEmbedProps({ id: target.noteId, title: target.title, content: '' }),
          note
        );
      } else {
        const text = new Text();
        text.insert(target.title || target.url, 0, { link: target.url });
        blockId = editor.doc.addBlock('affine:paragraph', { text }, note);
      }
      editor.doc.captureSync();
      return blockId;
    },
    hasAutoGeneratedFrames() {
      return editor.doc.getModelsByFlavour('affine:frame').some(frame => {
        const title = (frame as unknown as { title?: { toString(): string } }).title?.toString() ?? '';
        return isAutoGeneratedFrameTitle(title);
      });
    },
    selectedText() {
      // KEY-373: rich text lives in the light DOM, so the document selection is the editor selection.
      return (document.getSelection()?.toString() ?? '').trim();
    },
    async insertParagraphs(text: string) {
      const note = editor.doc.root?.children.find(child => child.flavour === 'affine:note');
      if (!note) throw new Error('missing-note-block');
      const lines = text.split(/\n+/).map(line => line.trim()).filter(Boolean);
      for (const line of lines) editor.doc.addBlock('affine:paragraph', { text: new Text(line) }, note);
      return lines.length;
    },
    async insertKanban(titleOrOptions?: string | { title?: string; lang?: 'ar' | 'en' }, maybeOptions?: { lang?: 'ar' | 'en' }) {
      const options = typeof titleOrOptions === 'object' ? titleOrOptions : maybeOptions;
      const title = typeof titleOrOptions === 'string' ? titleOrOptions : options?.title;
      const lang = options?.lang ?? bridge?.appearance?.()?.lang ?? ((document.documentElement.lang === 'ar' || document.documentElement.dir === 'rtl') ? 'ar' : 'en');
      return insertResearchKanban(editor.doc, undefined, { ...options, lang, title });
    },
    fitToScreen() {
      fitEdgelessScreen(editor);
    },
    setZoom(percent: number) {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const clamped = Math.max(0.2, Math.min(3, percent / 100));
      gfx.viewport.setZoom(clamped);
      return Math.round(gfx.viewport.zoom * 100);
    },
    zoomIn() {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const next = Math.min(3, Math.round((gfx.viewport.zoom + 0.2) * 100) / 100);
      gfx.viewport.setZoom(next);
      return Math.round(gfx.viewport.zoom * 100);
    },
    zoomOut() {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const next = Math.max(0.2, Math.round((gfx.viewport.zoom - 0.2) * 100) / 100);
      gfx.viewport.setZoom(next);
      return Math.round(gfx.viewport.zoom * 100);
    },
    async exportSources() {
      const job = transformer();
      const original = job.docToSnapshot(editor.doc);
      const snapshot = original && prepareApparatusExport(original);
      if (!snapshot) throw new Error('snapshot-export-failed');
      return {
        markdown: (await new MarkdownAdapter(job, editor.doc.provider).fromDocSnapshot({ snapshot })).file,
        html: (await new HtmlAdapter(job, editor.doc.provider).fromDocSnapshot({ snapshot })).file,
      };
    },
    scrollToBlock(blockId: string) {
      try {
        const el = editor.querySelector(`[data-block-id="${blockId}"]`) || editor.querySelector(`[id="${blockId}"]`);
        el?.scrollIntoView({ behavior: 'smooth', block: 'center' });
      } catch {}
    },
    async flush() { await flushApparatusSettings(); await blobs?.flush(); await scheduled; },
    dispose() { stopApparatusAppearance?.(); observedDoc.off('update', changed); workspace.forceStop(); workspace.dispose(); editor.remove(); },
  };
  if (bridge) {
    window.addEventListener('keydown', event => {
      if ((event.ctrlKey || event.metaKey) && (event.code === 'KeyS' || event.key.toLowerCase() === 's')) {
        event.preventDefault();
        void bridge.explicitSave().catch(bridge.error);
      }
    }, true);
    // KEY-370: a passage dragged from a BagLib reader becomes a source block in this chapter.
    document.addEventListener('dragover', event => { if (event.dataTransfer?.types.includes(SOURCE_DRAG_TYPE)) event.preventDefault(); });
    document.addEventListener('drop', event => {
      const payload = readSourceDrag(event.dataTransfer);
      if (!payload) return;
      event.preventDefault();
      event.stopPropagation();
      void session.insertSource(payload.kind, payload.props as unknown as Record<string, unknown>);
    }, true);
    // KEY-244: open BagLib links, quick-note embeds, and source blocks when clicked on canvas (even behind edgeless-note-mask).
    const isBaglibTargetUrl = (url: string) => /^(note|quran|sunnah|book|poetry|media|baglib):/i.test(url.trim());
    let downPos = { x: 0, y: 0 };
    document.addEventListener('pointerdown', event => { downPos = { x: event.clientX, y: event.clientY }; }, true);
    document.addEventListener('click', event => {
      if (Math.hypot(event.clientX - downPos.x, event.clientY - downPos.y) >= 5) return;
      for (const node of event.composedPath()) {
        if (node instanceof HTMLAnchorElement) {
          const href = node.getAttribute('href') || '';
          if (isBaglibTargetUrl(href)) {
            event.preventDefault();
            event.stopPropagation();
            void bridge.sources?.open(href).catch(bridge.error);
            return;
          }
        }
      }
      if (editor.mode !== 'edgeless') return;
      const inMask = event.composedPath().some(node => (node as HTMLElement)?.tagName?.toLowerCase() === 'edgeless-note-mask');
      if (!inMask) return;
      const { clientX: cx, clientY: cy } = event;
      const queryAllDeep = (root: ParentNode, selector: string): Element[] => {
        const out = Array.from(root.querySelectorAll(selector));
        for (const el of Array.from(root.querySelectorAll('*'))) {
          if (el.shadowRoot) out.push(...queryAllDeep(el.shadowRoot, selector));
        }
        return out;
      };
      for (const embed of queryAllDeep(editor, 'baglib-note-embed')) {
        const card = (embed.shadowRoot ?? embed).querySelector('.note-card');
        const rect = card?.getBoundingClientRect();
        if (rect && cx >= rect.left && cx <= rect.right && cy >= rect.top && cy <= rect.bottom) {
          const noteId = (embed as unknown as { model?: { props?: { noteId?: string } } }).model?.props?.noteId;
          if (noteId) {
            event.preventDefault();
            event.stopPropagation();
            void bridge.notes?.open(noteId).catch(bridge.error);
            return;
          }
        }
      }
      for (const src of queryAllDeep(editor, 'baglib-source-block')) {
        const card = (src.shadowRoot ?? src).querySelector('.source-card');
        const rect = card?.getBoundingClientRect();
        if (rect && cx >= rect.left && cx <= rect.right && cy >= rect.top && cy <= rect.bottom) {
          const url = (src as unknown as { model?: { props?: { url?: string } } }).model?.props?.url;
          if (url) {
            event.preventDefault();
            event.stopPropagation();
            void bridge.sources?.open(url).catch(bridge.error);
            return;
          }
        }
      }
    }, true);
    await bridge.connect(session);
  }

  // Retained for the isolated offline smoke test and native verification.
  (window as unknown as { __baglibResearchEditor: unknown }).__baglibResearchEditor = {
    ready: true,
    async exportSources() {
      const job = transformer();
      const original = job.docToSnapshot(editor.doc);
      const snapshot = original && prepareApparatusExport(original);
      if (!snapshot) throw new Error('snapshot-export-failed');
      return { markdown: (await new MarkdownAdapter(job, editor.doc.provider).fromDocSnapshot({ snapshot })).file, html: (await new HtmlAdapter(job, editor.doc.provider).fromDocSnapshot({ snapshot })).file };
    },
    editor,
    workspace,
    arrangeSources(options?: { lang?: 'ar' | 'en' }) {
      const lang = options?.lang ?? bridge?.appearance?.()?.lang ?? ((document.documentElement.lang === 'ar' || document.documentElement.dir === 'rtl') ? 'ar' : 'en');
      return arrangeSourcesOnCanvas(editor.doc, editor, { ...options, lang });
    },
    undoArrange() {
      return undoArrangeSources(editor.doc, editor);
    },
    insertKanban(titleOrOptions?: string | { title?: string; lang?: 'ar' | 'en' }, maybeOptions?: { lang?: 'ar' | 'en' }) {
      const options = typeof titleOrOptions === 'object' ? titleOrOptions : maybeOptions;
      const title = typeof titleOrOptions === 'string' ? titleOrOptions : options?.title;
      const lang = options?.lang ?? bridge?.appearance?.()?.lang ?? ((document.documentElement.lang === 'ar' || document.documentElement.dir === 'rtl') ? 'ar' : 'en');
      return insertResearchKanban(editor.doc, undefined, { ...options, lang, title });
    },
    fitToScreen() {
      fitEdgelessScreen(editor);
    },
    setZoom(percent: number) {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const clamped = Math.max(0.2, Math.min(3, percent / 100));
      gfx.viewport.setZoom(clamped);
      return Math.round(gfx.viewport.zoom * 100);
    },
    zoomIn() {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const next = Math.min(3, Math.round((gfx.viewport.zoom + 0.2) * 100) / 100);
      gfx.viewport.setZoom(next);
      return Math.round(gfx.viewport.zoom * 100);
    },
    zoomOut() {
      const host = editor.querySelector('editor-host') as { std?: { getOptional?: (id: unknown) => unknown; get?: (id: unknown) => unknown } } | null;
      const gfx = (host?.std?.getOptional?.(GfxControllerIdentifier) ?? host?.std?.get?.(GfxControllerIdentifier)) as {
        viewport?: { zoom: number; setZoom: (zoom: number) => void };
      } | undefined;
      if (!gfx?.viewport) return 100;
      const next = Math.max(0.2, Math.round((gfx.viewport.zoom - 0.2) * 100) / 100);
      gfx.viewport.setZoom(next);
      return Math.round(gfx.viewport.zoom * 100);
    },
    get mode() {
      return editor.mode;
    },
    setMode(mode: DocMode) {
      editor.switchEditor(mode);
      return editor.updateComplete;
    },
    async snapshot() {
      const job = new Transformer({
        schema,
        blobCRUD: workspace.blobSync,
        docCRUD: {
          create: (id: string) => workspace.createDoc(id).getStore({ id }),
          get: (id: string) => workspace.getDoc(id)?.getStore({ id }) ?? null,
          delete: (id: string) => workspace.removeDoc(id),
        },
      });
      return job.docToSnapshot(editor.doc);
    },
  };
  document.documentElement.dataset.researchEditorReady = 'true';
}

mount().catch(error => {
  console.error(error);
  bridge?.error(error);
  document.documentElement.dataset.researchEditorReady = 'error';
});
