const { app, clipboard, nativeImage } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const profile = process.env.BAGLIB_KEY363_PROFILE;
const evidence = process.env.BAGLIB_KEY363_EVIDENCE;
const phase = process.env.BAGLIB_KEY363_PHASE;
assert.equal(path.dirname(profile), fs.realpathSync('.baglib-data'));
app.setPath('userData', profile);
app.setAppPath(process.cwd());
app.commandLine.appendSwitch('remote-debugging-port', '9363');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
let running = false;
app.on('browser-window-created', (_event, win) => {
  const errors = [];
  win.webContents.on('console-message', (_e, level, message) => { if (level >= 3) errors.push(message); });
  win.webContents.on('did-finish-load', () => {
    if (running || win.webContents.getURL().startsWith('devtools:')) return;
    running = true;
    void run(win, errors).catch(async error => {
      console.error(error);
      fs.writeFileSync(path.join(evidence, phase + '-failure.txt'), String(error.stack) + '\n' + JSON.stringify(errors));
      try { fs.writeFileSync(path.join(evidence, phase + '-failure.png'), (await win.webContents.capturePage()).toPNG()); } catch {}
      app.exit(1);
    });
  });
});
async function run(win, errors) {
  fs.rmSync(path.join(evidence, phase+'-failure.txt'),{force:true}); fs.rmSync(path.join(evidence,phase+'-failure.png'),{force:true});
  win.setSize(1480, 1050); win.show();
  const evaluate = code => win.webContents.executeJavaScript(code, true);
  const editorFrame = () => win.webContents.mainFrame.frames.find(frame => frame.url.includes('/research-editor/'));
  const edit = code => { const frame = editorFrame(); assert.ok(frame, 'editor iframe'); return frame.executeJavaScript(code, true); };
  async function until(code, child = false) {
    for (let i = 0; i < 250; i++) { try { if (await (child ? edit(code) : evaluate(code))) return; } catch {} await pause(100); }
    throw new Error('timeout ' + code + '\n' + await evaluate('document.body.innerText'));
  }
  const screenshot = async name => { fs.writeFileSync(path.join(evidence, phase + '-' + name + '.png'), (await win.webContents.capturePage()).toPNG()); };
  const click = async selector => { await until(`!!document.querySelector(${JSON.stringify(selector)}) && !document.querySelector(${JSON.stringify(selector)}).disabled && !document.querySelector('fieldset:disabled')`); await evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`); await pause(150); };
  const input = async (selector, text) => {
    await evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(text)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`); await pause(150);
  };
  const labelClick = async text => click('[aria-label=' + JSON.stringify(text) + ']');
  // Production translations are read from the source via a JSON file generated by the runner command.
  const labels = JSON.parse(fs.readFileSync(path.join(evidence, 'translations.json'), 'utf8'));
  await until('!!window.electronAPI && !!document.querySelector("[data-nav-item=notes]")');
  await evaluate('window.electronAPI.settings.set("onboarding.v1",{seen:true})');
  await evaluate('location.reload()'); await pause(1300);
  await until('!!document.querySelector("[data-nav-item=notes]")');
  if (phase === 'missing') {
    assert.equal(await evaluate('window.electronAPI.researchEditor.available()'), false);
    assert.equal(await evaluate('!!document.querySelector("[data-nav-item=notes-editor]")'), false);
    await labelClick(labels.en.studyCommandSearch).catch(async () => labelClick(labels.ar.studyCommandSearch));
    await pause(200);
    const lang = await evaluate('document.documentElement.lang');
    const label = labels[lang].navEditor;
    await input('[role=dialog] input[type=search]', label);
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('[role=dialog] button span')).some(el=>el.textContent.trim()===${JSON.stringify(label)})`), false, 'palette hides unavailable editor');
    await screenshot('no-editor');
    fs.writeFileSync(path.join(evidence, phase + '-result.json'), JSON.stringify({ pass: true, errors })); app.exit(0); return;
  }
  await until('!!document.querySelector("[data-nav-item=notes-editor]")');
  const nav = await evaluate('Array.from(document.querySelectorAll("[data-nav-item]")).map(el=>el.dataset.navItem)');
  assert.equal(nav.indexOf('notes-editor') + 1, nav.indexOf('notes'));
  { const lang=await evaluate('document.documentElement.lang'); await labelClick(labels[lang].studyCommandSearch); await input('[role=dialog] input[type=search]',labels[lang].navEditor); await until(`Array.from(document.querySelectorAll('[role=dialog] button span')).some(el=>el.textContent.trim()===${JSON.stringify(labels[lang].navEditor)})`); await labelClick(labels[lang].studyClose); }
  await click('[data-nav-item=notes-editor]');
  await until('!!window.__baglibResearchEditorBridge');
  await until('window.__baglibResearchEditor?.ready', true);
  await edit('window.__nativeErrors=[];window.addEventListener("error",event=>window.__nativeErrors.push(String(event.error?.stack||event.message)))');
  assert.equal(await edit('location.origin'), await evaluate('location.origin'));
  const inputFile = path.join(evidence, 'documents.json');
  const documents = phase !== 'initial' && fs.existsSync(inputFile) ? JSON.parse(fs.readFileSync(inputFile, 'utf8')) : [];
  const setLang = async lang => {
    if (await evaluate('document.documentElement.lang') !== lang) await labelClick(labels[await evaluate('document.documentElement.lang')].toggleLanguage);
    await until(`document.documentElement.lang==='${lang}'`);
    await until(`document.documentElement.lang==='${lang}' && document.documentElement.dir==='${lang === 'ar' ? 'rtl' : 'ltr'}'`, true);
    assert.equal(await evaluate('document.querySelector("[data-nav-item=notes-editor]").textContent.trim()'), labels[lang].navEditor);
  };
  const open = async id => { await click('[data-document-id=' + JSON.stringify(id) + '] .manuscript-name'); await until(`window.__baglibResearchEditor.editor.doc.id===${JSON.stringify(id)}`, true); };
  const focus = async () => {
    await until(`(()=>{const e=window.__baglibResearchEditor.editor;const rt=e.querySelector('affine-paragraph rich-text');return !e.doc.readonly && !!rt?.inlineEditor && rt.inlineEditor.yText.doc?.guid===e.doc.spaceDoc.guid;})()`,true);
    await evaluate('document.querySelector("iframe").focus()');
    await edit(`(()=>{const rt=window.__baglibResearchEditor.editor.querySelector('affine-paragraph rich-text');if(!rt)throw Error('paragraph');const editor=window.__baglibResearchEditor.editor;if(editor.host?.event)editor.host.event.active=true;const el=rt.querySelector('[contenteditable="true"]')||rt;el.focus();rt.inlineEditor?.setInlineRange({index:rt.inlineEditor.yText.length,length:0});const range=document.createRange();const target=rt.querySelector('v-text')||el;range.selectNodeContents(target);range.collapse(false);const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);})()`);
  };
  win.webContents.debugger.attach('1.3');
  const key = async (key, code, modifiers = 0) => {
    await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', { type: 'keyDown', key, code, modifiers });
    await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', { type: 'keyUp', key, code, modifiers }); await pause(250);
  };
  if (phase === 'development') { fs.writeFileSync(path.join(evidence,'rea-ready.txt'),String(Date.now())); await pause(Number(process.env.BAGLIB_KEY363_REA_WAIT_MS || 0)); }
  if (phase === 'initial') {
    const manifest = JSON.parse(fs.readFileSync('tests/real-files/manifest.json', 'utf8'));
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
    const sourceEvidence = [];
    for (const lang of ['ar', 'en']) {
      await setLang(lang); const t = labels[lang];
      const file = manifest.files.find(item => item.kind === 'pdf' && item.lang === lang && item.textLayer === 'yes'); assert.ok(file);
      const task = pdfjs.getDocument({ data: new Uint8Array(fs.readFileSync(path.join('tests/real-files', file.path))), useSystemFonts: true, isEvalSupported: false });
      const pdf = await task.promise; let sample = '';
      for (let n = 1; n <= Math.min(pdf.numPages, 8) && sample.length < 140; n++) { sample += (await (await pdf.getPage(n)).getTextContent()).items.map(item => item.str || '').join(' ').normalize('NFKC') + ' '; }
      await task.destroy(); sample = sample.replace(/[\uE000-\uF8FF]/gu,'').replace(/\s+/gu,' ').slice(0,180).trim(); assert.ok(sample.length > 20);
      await input('[aria-label=' + JSON.stringify(t.manuscriptNew) + ']', lang + ' Research KEY-363');
      await click('.manuscript-list form button[type=submit]');
      await until('!!document.querySelector("[data-manuscript-tree]")');
      await input('[aria-label=' + JSON.stringify(t.manuscriptChapterNew) + ']', lang + ' Chapter');
      await click('[data-manuscript-tree] form button[type=submit]');
      await until('!!document.querySelector("[data-document-id]")');
      const id = await evaluate('Array.from(document.querySelectorAll("[data-document-id]")).at(-1).dataset.documentId');
      const typed = sample + (lang === 'en' ? ' ' + documents[0].sample.slice(0,60) : '');
      await open(id); await focus(); await pause(300);
      await win.webContents.debugger.sendCommand('Input.insertText', { text: typed }); await pause(1900);
      const saved = await evaluate(`window.electronAPI.manuscripts.document(${JSON.stringify(id)})`);
      fs.writeFileSync(path.join(evidence,'typing-'+lang+'.json'),JSON.stringify({saved,sample,snapshot:await edit('window.__baglibResearchEditor.snapshot()'),dom:await edit('({active:document.activeElement?.outerHTML,selection:window.getSelection()?.toString(),text:document.body.innerText,snapshot:window.__baglibResearchEditor.snapshot()})')},null,2));
      assert.ok(saved.plain_text.includes(sample.slice(0, 12)), 'typing autosaved real text');
      await focus(); await win.webContents.debugger.sendCommand('Input.insertText', { text: ' UNDOME' }); await pause(150);
      await key('z', 'KeyZ', 2);
      await until('!window.__baglibResearchEditor.editor.doc.root.children.map(x=>x.text?.toString()||"").join("").includes("UNDOME")', true).catch(() => undefined);
      await pause(1800);
      assert.ok(!(await evaluate(`window.electronAPI.manuscripts.document(${JSON.stringify(id)})`)).plain_text.includes('UNDOME'), 'editor undo');
      if (lang === 'ar') {
        const source = manifest.files.find(item => item.kind === 'pdf' && item.lang === 'ar' && item.textLayer === 'no') || file;
        const pdfimages = path.resolve('.baglib-data/pdf-engine/poppler/poppler-26.09.0/Library/bin/pdfimages.exe');
        execFileSync(pdfimages, ['-f','1','-l','1','-png',path.resolve('tests/real-files',source.path),path.join(evidence,'real-image')], { windowsHide: true });
        const image = fs.readdirSync(evidence).find(name => /^real-image.*\.png$/.test(name)); assert.ok(image, 'image extracted from a real PDF');
        const previousClipboard = { text: clipboard.readText(), html: clipboard.readHTML(), rtf: clipboard.readRTF(), image: clipboard.readImage() };
        try { clipboard.writeImage(nativeImage.createFromPath(path.join(evidence,image))); await focus(); win.webContents.paste(); await pause(700); }
        finally { clipboard.write(previousClipboard); }
        await pause(2500);fs.writeFileSync(path.join(evidence,'paste-probe.json'),JSON.stringify(await edit('({errors:window.__nativeErrors,text:document.body.innerText,blobs:window.__baglibResearchEditor.workspace.blobSync.sources.map(x=>x.name),html:document.querySelector("affine-editor-container").innerHTML})'),null,2));
        await until('!!document.querySelector("affine-image")', true); await pause(2000);
        const blobs = await evaluate('window.electronAPI.researchEditor.blobs.list()'); assert.ok(blobs.length > 0);
        assert.ok(fs.existsSync(path.join(profile,'data/manuscript-assets',blobs[0],'data')));
        assert.deepEqual(await edit('indexedDB.databases()'), []);
        sourceEvidence.push({ imageExtractedFrom: source.path, blob: blobs[0] });
      }
      const oldTheme = await edit('document.documentElement.dataset.theme');
      const oldFrame = editorFrame().routingId;
      await labelClick(t.toggleTheme); await until(`document.documentElement.dataset.theme!==${JSON.stringify(oldTheme)}`, true);
      await setLang(lang === 'ar' ? 'en' : 'ar'); await setLang(lang);
      assert.equal(editorFrame().routingId, oldFrame, 'appearance changes preserve iframe');
      await evaluate('document.documentElement.style.fontSize="20px"'); await until('document.documentElement.style.fontSize==="20px"', true);
      await evaluate('document.documentElement.style.fontSize="16px"');
      await focus();
      await win.webContents.debugger.sendCommand('Input.insertText', { text: ' ' + sample.slice(0,20) });
      await click('[data-document-id='+JSON.stringify(id)+'] button[aria-label='+JSON.stringify(t.manuscriptRename)+']');
      const renamed = lang + ' Chapter ' + sample.split(' ').slice(0,2).join(' ');
      await input('[aria-label='+JSON.stringify(t.manuscriptName)+']',renamed);
      await click('form:has(input[aria-label='+JSON.stringify(t.manuscriptName)+']) button[type=submit]');
      await until(`window.__baglibResearchEditor.editor.doc.root.props.title.toString()===${JSON.stringify(renamed)}`,true);
      await focus(); await key('s','KeyS',2); await pause(400);
      const final = await evaluate(`window.electronAPI.manuscripts.document(${JSON.stringify(id)})`);
      const exported = await edit('window.__baglibResearchEditor.snapshot()');
      assert.deepEqual(JSON.parse(final.snapshot), exported, 'saved snapshot matches exact editor export');
      documents.push({ id, lang, snapshot: final.snapshot, sample });
      sourceEvidence.push({ file: file.path, sample }); await screenshot(lang + '-editor');
    }
    fs.writeFileSync(inputFile, JSON.stringify(documents, null, 2));
    fs.writeFileSync(path.join(evidence,'real-inputs.json'), JSON.stringify(sourceEvidence,null,2));
    await focus(); await key('N','KeyN',10);
    await until('!!document.querySelector("[data-nav-item=notes][aria-current=page]")');
    await screenshot('global-new-note');
  } else {
    for (const item of documents) {
      await setLang(item.lang);
      const saved = await evaluate(`window.electronAPI.manuscripts.document(${JSON.stringify(item.id)})`);
      assert.equal(saved.snapshot, item.snapshot, 'exact stored snapshot after restart');
      await click('[data-manuscript-id=' + JSON.stringify(saved.manuscript_id) + '] .manuscript-name');
      await open(item.id);
      assert.deepEqual(await edit('window.__baglibResearchEditor.snapshot()'), JSON.parse(item.snapshot), 'exact BlockSuite round trip');
      if (item.lang === 'ar') { await until('!!document.querySelector("affine-image img") && document.querySelector("affine-image img").complete && document.querySelector("affine-image img").naturalWidth>0',true); assert.deepEqual(await edit('indexedDB.databases()'), []); }
      await screenshot(item.lang + '-reloaded');
    }
  }
  win.webContents.debugger.detach();
  assert.deepEqual(errors, [], 'no renderer errors');
  fs.writeFileSync(path.join(evidence,phase+'-result.json'), JSON.stringify({ pass: true, errors }, null, 2));
  await evaluate('window.__baglibResearchEditorBridge?.explicitSave()');
  if (phase === 'restart') {
    await evaluate('window.__baglibResearchEditorBridge.connect({load:async()=>{},flush:()=>new Promise(resolve=>setTimeout(resolve,6500)),dispose(){}})');
    win.close(); await pause(5200);
    assert.equal(win.isDestroyed(), false, 'native close waits beyond the five-second fallback');
    fs.writeFileSync(path.join(evidence,'slow-close.json'),JSON.stringify({heldBeyondFiveSeconds:true}));
    await pause(2500);
  } else { win.close(); await pause(600); }
  app.exit(0);
}
require(path.join(profile,'initialize.cjs')).initializeProfile();
require(path.resolve('dist/main/index.js'));
