import { app, nativeImage, BrowserWindow } from 'electron';
import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { getPdfPageCoverService } from '../../src/main/services/metadata/pdf-page-cover.service';
import { makePagePdf } from '../../tests/helpers/pdf-pages';
import { setupDatabaseIPC } from '../../src/main/ipc/database';
import { setupMetadataIPC } from '../../src/main/ipc/metadata';
import { getDatabase, closeDatabase } from '../../src/main/database/connection';
import { runMigrations } from '../../src/main/database/migrator';
import { migrations } from '../../src/main/database/migrations';
import { DigitalImportPipelineService } from '../../src/main/services/digital/digital-import-pipeline.service';
import { WorkRepository } from '../../src/main/database/repositories/work.repository';

const directory = process.env.BAGLIB_PDF_COVER_TEST_DIRECTORY!;
app.setPath('userData', path.join(directory, 'profile'));
app.setAppPath(process.cwd());
app.whenReady().then(async () => {
  const bitmap = Buffer.alloc(100 * 100 * 4);
  for (let offset = 0; offset < bitmap.length; offset += 4) { bitmap[offset] = 255; bitmap[offset + 3] = 255; }
  const logo = nativeImage.createFromBitmap(bitmap, { width: 100, height: 100 }).toJPEG(90);
  const pdf = path.join(directory, 'صفحات — pages.pdf');
  await fs.writeFile(pdf, makePagePdf(7, logo));
  const database = getDatabase();
  runMigrations(database, migrations);
  setupDatabaseIPC();
  setupMetadataIPC();
  const service = getPdfPageCoverService();
  const apiWindow = new BrowserWindow({ show: false, webPreferences: { preload: path.join(directory, 'preload.cjs'), contextIsolation: true } });
  try {
    const first = await service.render(pdf, 1);
    const cover = nativeImage.createFromPath(first.coverUrl);
    assert.equal(cover.isEmpty(), false);
    const pixel = cover.toBitmap();
    assert.ok(pixel[2] > 220 && pixel[0] < 35 && pixel[1] < 35, `Expected red page, got ${[...pixel.slice(0, 4)]}`);
    const choices = await service.renderPages(pdf);
    assert.deepEqual(choices.map(page => page.currentPage), [1, 2, 3, 4, 5]);
    assert.ok(choices.every(page => page.totalPages === 5 && page.documentPages === 7));
    assert.equal(new Set(choices.map(page => page.coverUrl)).size, 5);
    const second = nativeImage.createFromPath(choices[1].coverUrl).toBitmap();
    assert.ok(second[1] > 220 && second[0] < 35 && second[2] < 35);
    const short = path.join(directory, 'short.pdf');
    await fs.writeFile(short, makePagePdf(2, Buffer.alloc(0)));
    assert.equal((await service.renderPages(short)).length, 2);
    assert.equal((await service.render(pdf, 7)).currentPage, 5);
    await apiWindow.loadURL('data:text/html,<html><body></body></html>');
    const ipcPages = await apiWindow.webContents.executeJavaScript(`window.electronAPI.extractPdfCoverPages(${JSON.stringify(pdf)})`);
    assert.equal(ipcPages.success, true);
    assert.equal(ipcPages.pages.length, 5);
    const automatic = await apiWindow.webContents.executeJavaScript(`window.electronAPI.addBook(${JSON.stringify({ title: 'Automatic cover', author: 'Jane Austen', bookType: 'digital', filePath: pdf, digitalFormat: 'PDF', coverImage: 'https://invalid.example/unrelated.jpg' })})`);
    assert.equal(automatic.coverImage, first.coverUrl);
    const manual = await apiWindow.webContents.executeJavaScript(`window.electronAPI.addBook(${JSON.stringify({ title: 'Manual page choice', author: 'Jane Austen', bookType: 'digital', filePath: pdf, digitalFormat: 'PDF', coverImage: choices[2].coverUrl, metadataProvenance: { fieldSources: { coverImage: { source: 'manual_cover_selection', status: 'user_override', value: choices[2].coverUrl } } } })})`);
    assert.equal(manual.coverImage, choices[2].coverUrl);
    const pipeline = new DigitalImportPipelineService(new WorkRepository(database));
    const imported = await pipeline.importFile({ filePath: pdf, duplicateAction: 'import_anyway' });
    assert.equal(imported.success, true, imported.error);
    assert.equal(new WorkRepository(database).getById(imported.workId!)?.coverImage, first.coverUrl);
    const broken = path.join(directory, 'broken.pdf');
    await fs.writeFile(broken, '%PDF-1.4\ninvalid');
    await assert.rejects(service.render(broken));
    const recovered = path.join(directory, 'recovered.pdf');
    await fs.writeFile(recovered, makePagePdf(1, Buffer.alloc(0)));
    assert.ok((await service.render(recovered)).coverUrl);
    const realCover = await service.render(path.resolve('docs/31-10-2020-084952101 Essays That Will Change The Way You Think - Brianna Wiest.pdf'));
    const realImage = nativeImage.createFromPath(realCover.coverUrl);
    assert.equal(realImage.isEmpty(), false);
    assert.equal(realImage.getSize().width, 750);
    await fs.writeFile(path.join(directory, 'real-first-page.png'), realImage.toPNG());
    await fs.writeFile(path.join(directory, 'first-page.png'), cover.toPNG());
    console.log(JSON.stringify({ actualFirstPage: 'red', ignoredUnreferencedImage: 'blue', selectablePages: choices.length, totalDocumentPages: 7, shortDocumentChoices: 2, automaticAdditionUsesPageOne: true, manualChoicePreserved: true, importPipelineUsesPageOne: true, directory }));
  } finally { service.dispose(); apiWindow.destroy(); closeDatabase(); app.quit(); }
}).catch(error => { console.error(error); app.exit(1); });
