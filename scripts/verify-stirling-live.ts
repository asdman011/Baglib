import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, readFile, writeFile, utimes, readdir } from 'node:fs/promises';
import { StirlingSidecarService, checkJavaMajorVersion, probeStirlingReadiness, runStirlingPdf } from '../src/main/services/pdf-editor/stirling';
import { fileSha256 } from '../src/main/services/pdf-editor/source';
import { makePagePdf } from '../tests/helpers/pdf-pages';
import { inspectPdfFile } from '../src/main/services/pdf-editor/inspection';
import { StirlingProcessorService } from '../src/main/services/pdf-editor/processor';

async function main() {
  const root = path.resolve('.baglib-data/pdf-engine');
  const javaPath = path.join(root, 'java/jdk-25.0.5+8-jre/bin/java.exe');
  const jarPath = path.join(root, 'stirling/Stirling-PDF-server.jar');
  assert.equal(await checkJavaMajorVersion(javaPath), 25);
  const service = new StirlingSidecarService();
  try {
    const started = Date.now();
    const baseUrl = await service.ensureStarted({ javaPath, jarPath, workDir: path.join(root, 'stirling/live-verification'), startupTimeoutMs: 90_000 });
    await probeStirlingReadiness(baseUrl, new AbortController().signal, 10_000);
    const response = await fetch(baseUrl, { signal: AbortSignal.timeout(15_000) });
    assert.equal(response.status, 200);
    const body = await response.text();
    assert.ok(body.length > 0);
    const directory = path.join(root, 'stirling/live-verification', `run-${Date.now()}`);
    await mkdir(directory, { recursive: true });
    const filename = path.join(directory, 'source.pdf');
    const output = path.join(directory, 'rotated.pdf');
    await writeFile(filename, makePagePdf(2, Buffer.alloc(0)));
    const expectedHash = await fileSha256(filename);
    const inspected = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output, expectedHash, operation: 'inspect', language: 'ar' }, AbortSignal.timeout(30_000), () => {});
    assert.equal(inspected.totalPages, 2);
    assert.match((inspected.pages as { text: string }[])[1].text, /PAGE 2/u);
    const selected = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output, expectedHash, operation: 'inspect', language: 'en', payload: { fromPage: 2, toPage: 2 } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(selected.totalPages, 2);
    assert.deepEqual((selected.pages as { page: number }[]).map(page => page.page), [2]);
    const form = new FormData();
    form.set('fileInput', new Blob([new Uint8Array(await readFile(filename))], { type: 'application/pdf' }), 'source.pdf');
    form.set('lightweight', 'true');
    const textResponse = await fetch(`${baseUrl}/api/v1/convert/pdf/text-editor`, { method: 'POST', body: form, signal: AbortSignal.timeout(30_000) });
    assert.equal(textResponse.status, 200);
    const structuredText = await textResponse.json() as { pages: { pageNumber: number; width: number; height: number; textElements: { text: string; x: number; y: number; width: number; height: number }[] }[] };
    await writeFile(path.join(directory, 'structured-text.json'), JSON.stringify(structuredText, null, 2));
    assert.equal(structuredText.pages.length, 2);
    assert.match(structuredText.pages[0].textElements.map(element => element.text).join(''), /PAGE 1/u);
    console.log(JSON.stringify({ structuredText: structuredText.pages[0] }));
    const preview = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output, expectedHash, operation: 'preview', language: 'en', payload: { page: 2 } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(preview.page, 2);
    assert.equal(preview.width, 700);
    assert.equal(preview.height, 1000);
    assert.match(preview.image || '', /^data:image\/png;base64,/u);
    const batch = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output, expectedHash, operation: 'preview', language: 'ar', payload: { items: [{ page: 2 }, { page: 1 }] } }, AbortSignal.timeout(30_000), () => {});
    const thumbnails = batch.thumbnails as { key: string; page: number; image: string }[];
    assert.deepEqual(thumbnails.map(item => item.key), ['current:2', 'current:1']);
    for (const thumbnail of thumbnails) {
      const png = Buffer.from(thumbnail.image.split(',')[1], 'base64');
      assert.ok(png.readUInt32BE(16) <= 180);
      assert.ok(png.readUInt32BE(20) <= 240);
    }
    const result = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output, expectedHash, operation: 'organize', language: 'en', payload: { angle: 90 } }, AbortSignal.timeout(30_000), () => {});
    assert.ok(result.outputs?.length);
    const generated = await readFile(path.join(directory, result.outputs![0].filename));
    assert.equal(generated.subarray(0, 5).toString(), '%PDF-');
    const inspection = await inspectPdfFile(path.join(directory, result.outputs![0].filename), undefined, () => {});
    assert.equal(inspection.totalPages, 2);
    assert.deepEqual(inspection.pages.map(page => page.rotation), [90, 90]);
    assert.match(inspection.pages[0].text, /PAGE 1/u);
    assert.match(inspection.pages[1].text, /PAGE 2/u);
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'rotate', bytes: generated.length, originalUnchanged: true }));
    const planDirectory = path.join(directory, 'organize-split');
    const planResult = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output: path.join(planDirectory, 'document.pdf'), expectedHash, operation: 'organize', language: 'ar', payload: { pages: [{ page: 2, rotation: 90, splitAfter: true }, { blank: true }, { page: 1 }] } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(planResult.outputs?.length, 2);
    const firstPart = await inspectPdfFile(path.join(planDirectory, planResult.outputs![0].filename), undefined, () => {});
    const secondPart = await inspectPdfFile(path.join(planDirectory, planResult.outputs![1].filename), undefined, () => {});
    assert.equal(firstPart.totalPages, 1);
    assert.match(firstPart.pages[0].text, /PAGE 2/u);
    assert.equal(firstPart.pages[0].rotation, 90);
    assert.equal(secondPart.totalPages, 2);
    assert.equal(secondPart.pages[0].text.trim(), '');
    assert.match(secondPart.pages[1].text, /PAGE 1/u);
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'organize-split', reordered: true, rotated: true, blankInserted: true, parts: [1, 2], originalUnchanged: true }));
    const splitDirectory = path.join(directory, 'split');
    const splitResult = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output: path.join(splitDirectory, 'document.pdf'), expectedHash, operation: 'split', language: 'en', payload: { pages: [1] } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(splitResult.outputs?.length, 2);
    for (const [index, part] of splitResult.outputs!.entries()) {
      const document = await inspectPdfFile(path.join(splitDirectory, part.filename), undefined, () => {});
      assert.equal(document.totalPages, 1);
      assert.match(document.pages[0].text, new RegExp(`PAGE ${index + 1}`, 'u'));
    }
    console.log(JSON.stringify({ operation: 'native-split-endpoint', parts: 2, orderedText: true }));
    const inkDirectory = path.join(directory, 'ink');
    const ink = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output: path.join(inkDirectory, 'document.pdf'), expectedHash, operation: 'edit-content', language: 'en', payload: { edits: [{ kind: 'ink-signature', page: 2, rect: [30, 100, 230, 200], color: '#3b82f6', strokes: [[[0, 0], [1, 1]]] }] } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(ink.outputs?.length, 1);
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
    const inkTask = pdfjs.getDocument({ data: new Uint8Array(await readFile(path.join(inkDirectory, ink.outputs![0].filename))), verbosity: 0 });
    try {
      const document = await inkTask.promise;
      assert.equal(document.numPages, 2);
      const page = await document.getPage(2);
      assert.match((await page.getTextContent()).items.map(item => 'str' in item ? item.str : '').join(' '), /PAGE 2/u);
      assert.ok((await page.getOperatorList()).fnArray.includes(pdfjs.OPS.setStrokeRGBColor));
    } finally { await inkTask.destroy(); }
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'ink-overlay', originalUnchanged: true }));
    const tocDirectory = path.join(directory, 'toc');
    const toc = [{ title: 'المقدمة — Introduction', pageNumber: 1, children: [{ title: 'المبحث الثاني — Section 2', pageNumber: 2 }] }];
    const tocResult = await runStirlingPdf({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, { filename, output: path.join(tocDirectory, 'document.pdf'), expectedHash, operation: 'edit-toc', language: 'ar', payload: { toc, replaceExisting: true } }, AbortSignal.timeout(30_000), () => {});
    assert.equal(tocResult.outputs?.length, 1);
    const tocTask = pdfjs.getDocument({ data: new Uint8Array(await readFile(path.join(tocDirectory, tocResult.outputs![0].filename))), verbosity: 0 });
    try {
      const document = await tocTask.promise;
      const outline = await document.getOutline();
      assert.equal(outline?.length, 1);
      assert.equal(outline![0].title, toc[0].title);
      assert.equal(outline![0].items.length, 1);
      const child = outline![0].items[0];
      assert.equal(child.title, toc[0].children[0].title);
      assert.ok(Array.isArray(child.dest));
      assert.equal(await document.getPageIndex(child.dest[0]), 1);
      assert.equal(document.numPages, 2);
    } finally { await tocTask.destroy(); }
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'edit-toc', bilingualTitles: true, nestedDestinationPage: 2, originalUnchanged: true }));
    const processor = new StirlingProcessorService(path.join(directory, 'processor'));
    const pipelineResult = await processor.executePipeline({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, [filename], { name: 'Live full-path rotation', pipeline: [{ operation: '/api/v1/general/rotate-pdf', parameters: { angle: 90 } }] }, AbortSignal.timeout(30_000));
    const pipelineInspection = await inspectPdfFile(pipelineResult.outputPath, undefined, () => {});
    assert.equal(pipelineInspection.totalPages, 2);
    assert.deepEqual(pipelineInspection.pages.map(page => page.rotation), [90, 90]);
    assert.equal((await processor.getTelemetry()).processedToday, 1);
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'pipeline-full-path-rotate', output: pipelineResult.outputPath, originalUnchanged: true }));
    const standaloneResult = await processor.executePipeline({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }, [filename], { name: 'Standalone rotation', singleTool: true, pipeline: [{ operation: '/api/v1/general/rotate-pdf', parameters: { angle: 90 } }] }, AbortSignal.timeout(30_000));
    const standaloneInspection = await inspectPdfFile(standaloneResult.outputPath, undefined, () => {});
    assert.deepEqual(standaloneInspection.pages.map(page => page.rotation), [90, 90]);
    assert.equal(await fileSha256(filename), expectedHash);
    console.log(JSON.stringify({ operation: 'standalone-direct-rotate', originalUnchanged: true }));
    const inbox = path.join(directory, 'inbox');
    const outbox = path.join(directory, 'outbox');
    await mkdir(inbox);
    const watchedInput = path.join(inbox, 'watched.pdf');
    await writeFile(watchedInput, await readFile(filename));
    const archiveDirectory = path.join(inbox, '_archive');
    await mkdir(archiveDirectory);
    await writeFile(path.join(archiveDirectory, 'watched.pdf'), 'older archived original');
    const settledTime = new Date(Date.now() - 5000);
    await utimes(watchedInput, settledTime, settledTime);
    const now = new Date().toISOString();
    await processor.savePipeline({ id: 'live-watch', name: 'Live watched rotation', trigger: 'folder', active: true, afterProcessing: 'archive', createdAt: now, updatedAt: now, steps: [{ id: 'rotate', name: 'Rotate', operation: '/api/v1/general/rotate-pdf', parameters: { angle: 180 } }] });
    await processor.saveWatchedFolders([{ id: 'fixture-inbox', name: 'Disposable inbox', inputPath: inbox, outputPath: outbox, pipelineId: 'live-watch', status: 'watching', processedCount: 0 }]);
    const scan = await processor.checkWatchedFolders({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' });
    assert.deepEqual(scan, { processed: 1, errors: [] });
    const watchedOutputs = await readdir(outbox);
    assert.equal(watchedOutputs.length, 1);
    const watchedInspection = await inspectPdfFile(path.join(outbox, watchedOutputs[0]), undefined, () => {});
    assert.deepEqual(watchedInspection.pages.map(page => page.rotation), [180, 180]);
    assert.equal(await readFile(path.join(archiveDirectory, 'watched.pdf'), 'utf8'), 'older archived original');
    const archivedFiles = await readdir(archiveDirectory);
    assert.equal(archivedFiles.length, 2);
    assert.equal(await fileSha256(path.join(archiveDirectory, archivedFiles.find(file => file !== 'watched.pdf')!)), expectedHash);
    assert.equal((await processor.getWatchedFolders())[0].processedCount, 1);
    assert.deepEqual(await processor.checkWatchedFolders({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }), { processed: 0, errors: [] });
    console.log(JSON.stringify({ operation: 'watched-folder-archive', processed: 1, preservedArchivedSource: true, nextScanProcessed: 0 }));
    const keepPipeline = (await processor.listPipelines()).find(pipeline => pipeline.id === 'live-watch')!;
    await processor.savePipeline({ ...keepPipeline, afterProcessing: 'keep' });
    const keptInput = path.join(inbox, 'kept.pdf');
    await writeFile(keptInput, await readFile(filename));
    await utimes(keptInput, settledTime, settledTime);
    assert.deepEqual(await processor.checkWatchedFolders({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }), { processed: 1, errors: [] });
    const restartedProcessor = new StirlingProcessorService(path.join(directory, 'processor'));
    assert.deepEqual(await restartedProcessor.checkWatchedFolders({ stirlingUrl: baseUrl, python: '', script: '', tessdata: '' }), { processed: 0, errors: [] });
    assert.equal(await fileSha256(keptInput), expectedHash);
    console.log(JSON.stringify({ operation: 'watched-folder-keep', sourcePreserved: true, restartProcessed: 0 }));
    console.log(JSON.stringify({ javaMajor: 25, baseUrl, elapsedMs: Date.now() - started, status: response.status, contentType: response.headers.get('content-type'), responseBytes: Buffer.byteLength(body) }));
  } finally {
    await service.stop();
  }
}

void main().catch(error => { console.error(error); process.exitCode = 1; });
