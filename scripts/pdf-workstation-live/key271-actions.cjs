// Invoked by the real-app markup harness after restart. Uses the visible tools home and Save shortcut.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
module.exports = async function checkActions({ language, directory, win, evaluate, until, change, screenshot, key, inspect }) {
  const source = path.join(directory,language+'.pdf');
  const hash = () => crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
  const before = hash();
  const beforeAnnotations = inspect(source);
  win.setContentSize(1280,900);
  const toolsLabel = language === 'ar' ? '\u0623\u062f\u0648\u0627\u062a \u0648\u0645\u0639\u0627\u0644\u062c PDF' : 'PDF Tools & Processor';
  const allLabel = language === 'ar' ? '\u062c\u0645\u064a\u0639 \u0623\u062f\u0648\u0627\u062a PDF \u0648\u0627\u0644\u0645\u0639\u0627\u0644\u062c\u2026' : 'All PDF tools & processor\u2026';
  await until(`[...document.querySelectorAll('[data-pdf-header] button')].some(e=>e.title===${JSON.stringify(toolsLabel)})`);
  await evaluate(`[...document.querySelectorAll('[data-pdf-header] button')].find(e=>e.title===${JSON.stringify(toolsLabel)}).click()`);
  await until(`[...document.querySelectorAll('[data-pdf-header] button')].some(e=>e.textContent.trim()===${JSON.stringify(allLabel)})`);
  await evaluate(`[...document.querySelectorAll('[data-pdf-header] button')].find(e=>e.textContent.trim()===${JSON.stringify(allLabel)}).click()`);
  await until(`!!document.querySelector('[data-pdf-tools-hub] [data-pdf-saved-actions]')`);
  win.setContentSize(1280,900);
  await evaluate(`document.querySelector('[data-pdf-tools-hub] [data-pdf-saved-actions] details').open=true`);
  await change('[data-pdf-tools-hub] [data-action-name]', `KEY271 ${language} دراسة Study`);
  await evaluate(`document.querySelector('[data-pdf-tools-hub] [data-action-save]').click()`);
  await until(`document.querySelectorAll('[data-pdf-tools-hub] [data-action-run]').length>=${language==='ar'?1:2}`);
  await screenshot(`actions-${language}-1280`);
  win.setContentSize(480,900); await screenshot(`actions-${language}-480`);
  const ids=await evaluate(`[...document.querySelectorAll('[data-pdf-tools-hub] [data-action-run]')].map(e=>e.dataset.actionRun)`);
  await evaluate(`document.querySelector('[data-pdf-tools-hub] [data-action-run="${ids.at(-1)}"]').click()`);
  await until(`['completed','failed','cancelled'].includes(document.querySelector('[data-pdf-workstation]').dataset.pdfJobState)`);
  const status = await evaluate(`window.electronAPI.pdfEditor.status(document.querySelector('[data-pdf-workstation]').dataset.pdfJobId)`);
  fs.writeFileSync(path.join(directory,'action-status-'+language+'.json'),JSON.stringify(status,null,2));
  assert.equal(status.data?.state,'completed',JSON.stringify(status));
  await until(`document.querySelector('[data-pdf-save-state]')?.dataset.pdfSaveState==='staged'`);
  assert.equal(hash(),before,'Running actions must only stage');
  await screenshot(`action-staged-${language}-480`);
  await key('s',true); await until(`document.querySelector('[data-pdf-save-state]')?.dataset.pdfSaveState==='saved'`);
  assert.notEqual(hash(),before,'Save should publish the staged output');
  const after=inspect(source);
  assert.equal(after.outside,beforeAnnotations.outside);
  assert.equal(after.owned,beforeAnnotations.owned);
  const files=fs.readdirSync(path.join(directory,'emergency-copies')).filter(file=>file.endsWith('.pdf'));
  assert.equal(files.length,2,'One emergency copy for each of the two real PDF sources');
  assert.equal(files.filter(file=>file.endsWith('.next.pdf')).length,0);
  return {before, after, emergencyFiles:files};
};
